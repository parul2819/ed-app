// Kid-friendly-ui skill, section 6: build pipeline for random background images.
// Reads whatever files currently exist in the source folder (no hardcoded count/list),
// optimizes each into frontend/public/backgrounds/ as webp, and regenerates
// frontend/src/backgroundManifest.js from the actual output. Re-run whenever images
// are added to or removed from the source folder.

import { readdir, mkdir, rm, writeFile } from "node:fs/promises";
import { join, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const SOURCE_DIR = join(__dirname, "..", "..", "background images");
const OUTPUT_DIR = join(__dirname, "..", "public", "backgrounds");
const MANIFEST_PATH = join(__dirname, "..", "src", "backgroundManifest.js");
const MAX_DIMENSION = 1600;
const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

async function main() {
  let sourceEntries;
  try {
    sourceEntries = await readdir(SOURCE_DIR, { withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") {
      console.error(`Source folder not found: ${SOURCE_DIR}`);
      process.exit(1);
    }
    throw err;
  }

  const sourceFiles = sourceEntries
    .filter((entry) => entry.isFile() && IMAGE_EXTENSIONS.has(extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort();

  if (sourceFiles.length === 0) {
    console.error(`No images found in ${SOURCE_DIR}`);
    process.exit(1);
  }

  await rm(OUTPUT_DIR, { recursive: true, force: true });
  await mkdir(OUTPUT_DIR, { recursive: true });

  const outputFilenames = [];
  for (const filename of sourceFiles) {
    const srcPath = join(SOURCE_DIR, filename);
    const outName = `${basename(filename, extname(filename))}.webp`;
    const outPath = join(OUTPUT_DIR, outName);

    await sharp(srcPath)
      .resize({ width: MAX_DIMENSION, height: MAX_DIMENSION, fit: "inside", withoutEnlargement: true })
      .webp({ quality: 78 })
      .toFile(outPath);

    outputFilenames.push(outName);
  }

  const manifestSource = `// Auto-generated by scripts/build-backgrounds.mjs — do not edit by hand.
// Re-run \`npm run build:backgrounds\` after adding/removing files in
// "${SOURCE_DIR.replaceAll("\\", "/")}".
export const BACKGROUND_IMAGES = ${JSON.stringify(outputFilenames, null, 2)};
`;

  await writeFile(MANIFEST_PATH, manifestSource, "utf8");

  console.log(`Wrote ${outputFilenames.length} background images to ${OUTPUT_DIR}`);
  console.log(`Wrote manifest: ${MANIFEST_PATH}`);
}

main();
